def f64(*xs):
    return [x.astype(np.float64) for x in xs]


def softmax(x, axis=-1):
    m = x.max(axis=axis, keepdims=True)
    e = np.exp(x - m)
    return e / e.sum(axis=axis, keepdims=True)


def erf(x):
    from scipy.special import erf as _erf

    return _erf(x)


